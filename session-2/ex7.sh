#!/bin/bash

# Запрашиваем день недели
echo "Привет, какой сегодня день недели?"
read DAY

# Выводим подтверждение
echo "Уже $DAY"

# Запрашиваем число
echo "Какое сегодня число?"
read DATE

# Выводим фразу с обеими переменными
echo "Не думал что $DAY будет $DATE числа"

# Сохраняем текущую дату в переменную
CURRENT_DATE=$(date)

# Выводим дату
echo "Я считаю что сегодня $CURRENT_DATE"
